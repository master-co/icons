import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {unzipSync,strFromU8} from 'fflate'
for(const locale of ['', '/tw'])test(`stroke slider exports matching geometry ${locale}`,async({page})=>{
 await page.goto(`${locale}/icons?q=bell-off&size=16&stroke=1&corner=rounded`)
 await expect(page.locator('astro-island[ssr]')).toHaveCount(0)
 const slider=page.getByRole('slider',{name:locale?'線寬':'Stroke width',exact:true})
 await expect(slider).toHaveValue('1')
 await slider.press('End');await expect(slider).toHaveValue('1.5')
 await expect(page).toHaveURL(/stroke=1.5/)
 await expect(page.locator('.explorer-icon svg').first()).toHaveAttribute('stroke-width','1.5')
 await page.reload();await expect(slider).toHaveValue('1.5')
 await page.locator('.explorer-tile').first().click()
 const dialog=page.getByRole('dialog'),code=dialog.locator('textarea')
 await expect(code).toHaveValue(/stroke-width="1.5"/)
 await expect(code).toHaveValue(/<mask /)
 await expect(dialog.locator('.master-cell svg')).toHaveCount(9)
 const download=page.waitForEvent('download');await dialog.getByRole('link',{name:locale?'下載 SVG':'Download SVG',exact:true}).click()
 const svg=await readFile((await (await download).path())!,'utf8')
 expect(svg).toContain(await code.inputValue())
 await dialog.getByRole('button',{name:locale?'關閉':'Close',exact:true}).click()
 const zipDownload=page.waitForEvent('download');await page.getByRole('link',{name:locale?'下載此組':'Download set',exact:true}).click()
 const zip=await zipDownload;expect(zip.suggestedFilename()).toBe('master-icons-16-rounded-stroke-1.5.zip')
 const entries=unzipSync(await readFile((await zip.path())!));expect(strFromU8(entries['bell-off.svg'])).toBe(svg)
 await page.getByRole('button',{name:locale?'重設線寬':'Reset stroke',exact:true}).click()
 await expect(slider).toHaveValue('1.25');await expect(page).not.toHaveURL(/stroke=/)
 await slider.press('Home');await slider.press('ArrowRight');await expect(slider).toHaveValue('1')
})
test('invalid widths fall back to optical defaults and stroke survives navigation',async({page})=>{
 await page.goto('/icons?stroke=Infinity&size=20')
 await expect(page.getByRole('slider',{name:'Stroke width',exact:true})).toHaveValue('1.5')
 await page.getByRole('slider',{name:'Stroke width',exact:true}).press('ArrowRight')
 await page.getByRole('button',{name:'Size comparison',exact:true}).click()
 await expect(page.locator('.optical-row').first().locator('.explorer-icon')).toHaveCount(3)
 const category=page.getByRole('navigation',{name:'Category',exact:true}).getByRole('link').nth(1)
 await expect(category).toHaveAttribute('href',/stroke=1.75/)
 await category.click();await expect(page).toHaveURL(/stroke=1.75/)
})

test('optical size bounds clamp URLs, size changes, comparisons and exports',async({page})=>{
 await page.goto('/icons?size=16&stroke=2.5&q=sliders')
 const stroke=page.getByRole('slider',{name:'Stroke width',exact:true}),size=page.getByRole('slider',{name:'Display size',exact:true})
 await expect(stroke).toHaveAttribute('min','0.75');await expect(stroke).toHaveAttribute('max','1.5');await expect(stroke).toHaveValue('1.5')
 await expect(page).toHaveURL(/stroke=1.5/)
 await size.press('ArrowRight');await expect(stroke).toHaveAttribute('min','1');await expect(stroke).toHaveAttribute('max','2')
 await stroke.press('End');await expect(stroke).toHaveValue('2')
 await size.press('ArrowLeft');await expect(stroke).toHaveValue('1.5')
 await stroke.press('Home');await expect(stroke).toHaveValue('0.75')
 await size.press('End');await expect(stroke).toHaveAttribute('min','1.25');await expect(stroke).toHaveAttribute('max','2.5');await expect(stroke).toHaveValue('1.25')
 await stroke.press('End');await page.getByRole('button',{name:'Size comparison',exact:true}).click()
 const masks=page.locator('.optical-row').first().locator('.explorer-icon')
 for(const [i,s,w] of [[0,16,1.5],[1,20,2],[2,24,2.5]]){await expect(masks.nth(i).locator('svg')).toHaveAttribute('stroke-width',String(w));await expect(masks.nth(i).locator('svg')).toHaveAttribute('viewBox',`0 0 ${s} ${s}`)}
 await page.locator('.explorer-tile').first().click()
 const masters=page.getByRole('dialog').locator('.master-row').filter({has:page.locator('.master-cell')}).first().locator('svg')
 for(const [i,w] of [[0,1.5],[1,2],[2,2.5]])await expect(masters.nth(i)).toHaveAttribute('stroke-width',String(w))
})
