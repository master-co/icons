test('optical size bounds clamp URLs, size changes, comparisons and exports',async({page})=>{
 await page.goto('/icons?size=16&stroke=2.5&q=sliders')
 const stroke=page.getByRole('slider',{name:'Stroke width',exact:true}),size=page.getByRole('slider',{name:'Display size',exact:true})
 await expect(stroke).toHaveAttribute('min','0.75');await expect(stroke).toHaveAttribute('max','1.5');await expect(stroke).toHaveValue('1.5')
 await expect(page).toHaveURL(/stroke=1.5/)
 await size.press('ArrowRight');await expect(stroke).toHaveAttribute('min','1');await expect(stroke).toHaveAttribute('max','2')
 await stroke.press('End');await expect(stroke).toHaveValue('2')
 await size.press('ArrowLeft');await expect(stroke).toHaveValue('1.5')
 await stroke.press('Home');await expect(stroke).toHaveValue('0.75')
 await size.press('End');await expect(stroke).toHaveAttribute('min','1.25');await expect(stroke).toHaveAttribute('max','2.5');await expect(stroke).toHaveValue('1.25')
 await stroke.press('End');await page.getByRole('button',{name:'Size comparison',exact:true}).click()
 const masks=page.locator('.optical-row').first().locator('.explorer-icon')
 for(const [i,s,w] of [[0,16,1.5],[1,20,2],[2,24,2.5]]){await expect(masks.nth(i).locator('svg')).toHaveAttribute('stroke-width',String(w));await expect(masks.nth(i).locator('svg')).toHaveAttribute('viewBox',`0 0 ${s} ${s}`)}
 await page.locator('.explorer-tile').first().click()
 const masters=page.getByRole('dialog').locator('.master-row').filter({has:page.locator('.master-cell')}).first().locator('svg')
 for(const [i,w] of [[0,1.5],[1,2],[2,2.5]])await expect(masters.nth(i)).toHaveAttribute('stroke-width',String(w))
})
