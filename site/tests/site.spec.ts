import {test,expect} from '@playwright/test'
for(const [locale,heading,search] of [['','Find the right shape.','Search icons'],['/tw','找到適合的圖形。','搜尋圖示']]){
 test(`${locale||'en'} collection filters, URL, details, copy fallback and downloads`,async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(`${locale}/icons?size=20&corner=rounded&q=search`)
  await expect(page.getByRole('heading',{name:heading})).toBeVisible()
  const input=page.getByRole('searchbox',{name:search,exact:true})
  await expect(input).toHaveValue('search')
  await expect(page.locator('input[name=size][value="20"]')).toBeChecked()
  await expect(page.locator('input[name=corner][value=rounded]')).toBeChecked()
  await input.fill('no-icon-with-this-name')
  await expect(page.getByTestId('result-count')).toContainText('0')
  await expect(page.getByTestId('icon-grid').locator('button')).toHaveCount(0)
  await input.fill('search')
  await page.getByTestId('icon-grid').locator('button').filter({has:page.locator('.icon-name',{hasText:/^search$/})}).click()
  const dialog=page.locator('dialog.icon-dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('.master-cell svg')).toHaveCount(9)
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>Promise.reject(new Error('denied'))},configurable:true}))
  await dialog.getByRole('button',{name:locale?'複製 SVG':'Copy SVG',exact:true}).click()
  await expect(dialog.getByRole('status')).toContainText(locale?'手動複製':'Copy manually')
  await expect(dialog.locator('textarea')).toBeFocused()
  const download=page.waitForEvent('download');await dialog.getByRole('link',{name:locale?'下載 SVG':'Download SVG',exact:true}).click();expect((await download).suggestedFilename()).toBe('search.svg')
  await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible()
  await expect(page.getByTestId('icon-grid').locator('button').filter({has:page.locator('.icon-name',{hasText:/^search$/})})).toBeFocused()
  const zip=page.waitForEvent('download');await page.getByRole('link',{name:locale?'下載此組':'Download set',exact:true}).click();expect((await zip).suggestedFilename()).toBe('master-icons-20-rounded.zip')
  expect(errors).toEqual([])
 })
 test(`${locale||'en'} home and all guide editions`,async({page})=>{
  await page.goto(locale||'/')
  await expect(page.locator('h1')).toContainText(locale?'安靜的線條':'Quiet lines')
  await page.getByRole('link',{name:locale?'探索圖示':'Explore icons',exact:false}).click()
  await expect(page).toHaveURL(new RegExp(`${locale}/icons`))
  for(const slug of ['getting-started','svg','react','optical-sizes','accessibility','license']){
   const result=await page.goto(`${locale}/guide/${slug}`);expect(result?.status()).toBe(200)
   await expect(page.locator('html')).toHaveAttribute('lang',locale?'zh-TW':'en')
   await expect(page.locator('h1')).toBeVisible()
  }
 })
}
test('invalid URL, pagination, mobile, optical comparison and failed details',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'})
 await page.goto('/icons?size=17&corner=invalid&page=Infinity&category=nope')
 await expect(page.locator('input[name=size][value="24"]')).toBeChecked()
 await expect(page.getByTestId('icon-grid').locator('button')).toHaveCount(96)
 await page.getByRole('button',{name:'Next',exact:true}).click()
 await expect(page).toHaveURL(/page=2/)
 await page.getByRole('button',{name:'Size comparison',exact:true}).click()
 await expect(page.getByTestId('icon-grid').locator('button')).toHaveCount(24)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.route('**/data/*.json',route=>route.fulfill({status:503,body:'Unavailable'}))
 await page.getByTestId('icon-grid').locator('button').first().click()
 await expect(page.getByRole('alert')).toContainText('Unable to load')
 await page.unroute('**/data/*.json');await page.getByRole('button',{name:'Retry',exact:true}).click()
 await expect(page.locator('.master-cell svg')).toHaveCount(9)
})
